"""Uploaded files on local disk, under settings.upload_dir.

Paths stored in the database are relative and generated by the server, and
every lookup re-checks that the resolved path stays inside upload_dir.
"""

from pathlib import Path

from app.core.config import settings


def save(relative_path: str, data: bytes) -> None:
    destination = settings.upload_dir / relative_path
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_bytes(data)


def resolve(relative_path: str | None) -> Path | None:
    """Absolute path of a stored file, if it exists inside upload_dir."""
    if not relative_path:
        return None
    root = settings.upload_dir.resolve()
    path = (root / relative_path).resolve()
    if not path.is_relative_to(root) or not path.is_file():
        return None
    return path


def remove(relative_path: str | None) -> None:
    path = resolve(relative_path)
    if path is not None:
        path.unlink(missing_ok=True)
